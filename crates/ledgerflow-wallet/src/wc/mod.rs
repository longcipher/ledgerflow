//! WalletConnect v2 dApp client and [`WalletSigner`] adapter.
//!
//! [`WcV2Signer`] implements the [`WalletSigner`] capability interface over a
//! standard WalletConnect v2 session. It acts as the **dApp** side: it connects
//! to a WC v2 relay, pairs with a wallet (e.g. OneCipher) via a pairing URI,
//! establishes a session, and routes signing requests through the relay.
//!
//! The protocol layer is self-contained (no dependency on any specific wallet
//! implementation), preserving LedgerFlow's design red line of wallet
//! neutrality. The crypto follows the official `@walletconnect/utils`
//! reference implementation (X25519 + HKDF-SHA256 key agreement,
//! ChaCha20-Poly1305 envelopes).

